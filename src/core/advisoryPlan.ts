export interface AdvisoryPlanResult {
  courseSemesterMap: Record<string, string>;
  courseColumnMap: Record<string, number>;
  isAutoGenerated: boolean;
  maxYears: number;
  maxRegularSemesters: number;
  allowedSemesterNames: string[];
}

/**
 * Determine degree duration (2, 4, or 5 years) strictly aligned with official PTUK credit caps.
 */
export function resolveMajorDegreeYears(
  totalCredits?: number,
  majorId?: string,
  majorName?: string,
): {
  maxYears: number;
  maxRegularSemesters: number;
  allowedSemesterNames: string[];
} {
  const cleanId = (majorId || "").toLowerCase();
  const cleanName = (majorName || "").toLowerCase();
  const isCse =
    cleanId.includes("cse") ||
    cleanId.includes("أنظمة-الحاسوب") ||
    cleanId.includes("أنظمة الحاسوب") ||
    cleanName.includes("أنظمة الحاسوب");

  const isDiploma =
    (totalCredits && totalCredits <= 80) ||
    cleanId.includes("diploma") ||
    cleanId.includes("دبلوم") ||
    cleanName.includes("دبلوم");

  const isFiveYearEngineering =
    Boolean(totalCredits && totalCredits > 140) ||
    isCse ||
    (cleanName.includes("هندسة") &&
      !cleanName.includes("برمجيات") &&
      !cleanName.includes("الذكاء") &&
      !cleanName.includes("حاسوب"));

  let maxYears = 4;
  if (isDiploma) {
    maxYears = 2; // دبلوم متوسط (سنتان / 4 فصول)
  } else if (isFiveYearEngineering) {
    maxYears = 5; // بكالوريوس هندسة 5 سنوات (160+ ساعة)
  }

  const maxRegularSemesters = maxYears * 2;
  const allowedSemesterNames = REGULAR_SEMESTER_NAMES.slice(
    0,
    maxRegularSemesters,
  );

  return { maxYears, maxRegularSemesters, allowedSemesterNames };
}



/**
 * Parse an explicit semester string into a 0-based column index.
 */
export function parseExplicitSemesterIndex(
  semStr?: string,
  maxSemesters = 10,
): number | null {
  if (!semStr || typeof semStr !== "string") return null;
  const normalized = semStr.trim();
  if (typeof SEMESTER_INDEX_MAP[normalized] === "number") {
    const idx = SEMESTER_INDEX_MAP[normalized];
    return Math.min(maxSemesters - 1, Math.max(0, idx));
  }

  let y = 0;
  if (
    normalized.includes("الأولى") ||
    normalized.includes("الاولى") ||
    normalized.includes("سنة 1") ||
    normalized.includes("السنة 1")
  ) {
    y = 1;
  } else if (
    normalized.includes("الثانية") ||
    normalized.includes("الثانيه") ||
    normalized.includes("سنة 2") ||
    normalized.includes("السنة 2")
  ) {
    y = 2;
  } else if (
    normalized.includes("الثالثة") ||
    normalized.includes("الثالثه") ||
    normalized.includes("سنة 3") ||
    normalized.includes("السنة 3")
  ) {
    y = 3;
  } else if (
    normalized.includes("الرابعة") ||
    normalized.includes("الرابعه") ||
    normalized.includes("سنة 4") ||
    normalized.includes("السنة 4")
  ) {
    y = 4;
  } else if (
    normalized.includes("الخامسة") ||
    normalized.includes("الخامسه") ||
    normalized.includes("سنة 5") ||
    normalized.includes("السنة 5")
  ) {
    y = 5;
  }

  if (y > 0) {
    const isSem2 =
      normalized.includes("الثاني") ||
      normalized.includes("ثاني") ||
      normalized.includes("2");
    const idx = (y - 1) * 2 + (isSem2 ? 1 : 0);
    return Math.min(maxSemesters - 1, Math.max(0, idx));
  }

  return null;
}

/**
 * Topologically and load-balanced Advisory Plan Solver for any university major.
 * Prevents prerequisite inversions, respects degree length, and balances credit loads.
 */
export function computeDynamicAdvisoryPlan(
  courses: Course[],
  options?: { totalCredits?: number; majorId?: string },
): AdvisoryPlanResult {
  const { totalCredits, majorId } = options || {};
  const { maxYears, maxRegularSemesters, allowedSemesterNames } =
    resolveMajorDegreeYears(totalCredits, majorId);

  const courseSemesterMap: Record<string, string> = {};
  const courseColumnMap: Record<string, number> = {};

  if (!Array.isArray(courses) || courses.length === 0) {
    return {
      courseSemesterMap,
      courseColumnMap,
      isAutoGenerated: false,
      maxYears,
      maxRegularSemesters,
      allowedSemesterNames,
    };
  }

  const courseMap = new Map<string, Course>();
  courses.forEach((c) => courseMap.set(c.id, c));

  const isCSE = isCseMajor(majorId);

  // 1. Identify which courses already have verified official semesters
  let explicitCount = 0;
  courses.forEach((c) => {
    let resolvedIdx: number | null = null;
    const explicitStr = c.semester || c.recommendedSemester;
    if (explicitStr) {
      resolvedIdx = parseExplicitSemesterIndex(explicitStr, maxRegularSemesters);
    } else if (isCSE && courseRecommendedSemesters[c.id]) {
      resolvedIdx = parseExplicitSemesterIndex(
        courseRecommendedSemesters[c.id],
        maxRegularSemesters,
      );
    }

    if (resolvedIdx !== null) {
      courseColumnMap[c.id] = resolvedIdx;
      courseSemesterMap[c.id] = allowedSemesterNames[resolvedIdx] || REGULAR_SEMESTER_NAMES[resolvedIdx];
      explicitCount++;
    }
  });

  const allHaveExplicit = explicitCount === courses.length;
  let isAutoGenerated = !allHaveExplicit;

  // If some or all courses lack explicit semesters, compute topological layout
  if (!allHaveExplicit) {
    // Build adjacency and prerequisite relationships within this major's courses
    const prereqGraph = new Map<string, string[]>();
    const downstreamGraph = new Map<string, string[]>();

    courses.forEach((c) => {
      prereqGraph.set(c.id, []);
      downstreamGraph.set(c.id, []);
    });

    courses.forEach((c) => {
      const pList = Array.isArray(c.prerequisites) ? c.prerequisites : [];
      pList.forEach((p) => {
        const pId = String(p).trim();
        if (courseMap.has(pId)) {
          prereqGraph.get(c.id)!.push(pId);
          downstreamGraph.get(pId)!.push(c.id);
        }
      });
    });

    // Helper: compute prerequisite chain depth (distance from earliest root)
    const memoDepth = new Map<string, number>();
    function getPrereqDepth(id: string, visited = new Set<string>()): number {
      if (memoDepth.has(id)) return memoDepth.get(id)!;
      if (visited.has(id)) return 0; // prevent circular reference
      visited.add(id);

      const prereqs = prereqGraph.get(id) || [];
      if (prereqs.length === 0) {
        memoDepth.set(id, 0);
        return 0;
      }

      let maxParentDepth = 0;
      for (const pId of prereqs) {
        const d = getPrereqDepth(pId, new Set(visited));
        if (d + 1 > maxParentDepth) maxParentDepth = d + 1;
      }
      memoDepth.set(id, maxParentDepth);
      return maxParentDepth;
    }

    // Step 2: Establish earliest valid semester for each course
    const minAllowedColumn = new Map<string, number>();
    courses.forEach((c) => {
      const depth = getPrereqDepth(c.id);
      let earliest = Math.min(maxRegularSemesters - 1, depth);

      // Domain-specific placement hints
      const name = c.name || "";
      const cat = c.category || "";

      // Remedial and foundation courses -> Semester 1 (index 0)
      if (cat.includes("استدراكي") || name.includes("استدراكي")) {
        earliest = 0;
      }

      // Capstone / Graduation projects -> Final year
      if (
        c.isGraduationProject ||
        name.includes("مشروع تخرج (2)") ||
        name.includes("مشروع 2") ||
        name.includes("مشروع التخرج 2")
      ) {
        earliest = Math.max(earliest, maxRegularSemesters - 1);
      } else if (
        name.includes("مشروع تخرج (1)") ||
        name.includes("مشروع 1") ||
        name.includes("مشروع التخرج 1")
      ) {
        earliest = Math.max(earliest, Math.max(0, maxRegularSemesters - 2));
      } else if (name.includes("تدريب ميداني") || name.includes("تدريب عملي")) {
        earliest = Math.max(earliest, Math.max(0, maxRegularSemesters - 3));
      }

      minAllowedColumn.set(c.id, earliest);
    });

    // Step 3: Priority sorting for scheduling
    // Courses with already-known explicit columns stay fixed
    // Unassigned courses ordered by:
    // 1. Minimum allowed semester (earlier depths first)
    // 2. Downstream dependents count (unlocking bottlenecks first)
    // 3. Compulsory before elective
    const unassignedCourses = courses.filter(
      (c) => typeof courseColumnMap[c.id] !== "number",
    );

    unassignedCourses.sort((a, b) => {
      const minA = minAllowedColumn.get(a.id) || 0;
      const minB = minAllowedColumn.get(b.id) || 0;
      if (minA !== minB) return minA - minB;

      const downA = downstreamGraph.get(a.id)?.length || 0;
      const downB = downstreamGraph.get(b.id)?.length || 0;
      if (downA !== downB) return downB - downA;

      const aIsElec = a.category?.includes("اختياري") ? 1 : 0;
      const bIsElec = b.category?.includes("اختياري") ? 1 : 0;
      return aIsElec - bIsElec;
    });

    // Step 4: Semester Load Balancing (Target 15-18 credits per semester, max 19)
    const semesterBuckets: Course[][] = Array.from(
      { length: maxRegularSemesters },
      () => [],
    );

    // Pre-seed buckets with explicitly fixed courses
    courses.forEach((c) => {
      if (typeof courseColumnMap[c.id] === "number") {
        const col = courseColumnMap[c.id];
        if (col >= 0 && col < maxRegularSemesters) {
          semesterBuckets[col].push(c);
        }
      }
    });

    for (const c of unassignedCourses) {
      const minCol = minAllowedColumn.get(c.id) || 0;
      const credits = Math.max(1, c.credits || 3);

      // Search for the earliest semester >= minCol that has capacity
      let bestCol = minCol;
      let minLoadInWindow = Infinity;

      for (let col = minCol; col < maxRegularSemesters; col++) {
        const currentCredits = semesterBuckets[col].reduce(
          (sum, item) => sum + Math.max(1, item.credits || 3),
          0,
        );

        // Standard semester upper capacity is 18-19 credits
        if (currentCredits + credits <= 18) {
          bestCol = col;
          break;
        }

        if (currentCredits < minLoadInWindow) {
          minLoadInWindow = currentCredits;
          bestCol = col;
        }
      }

      semesterBuckets[bestCol].push(c);
      courseColumnMap[c.id] = bestCol;
    }

    // Step 5: Strict Invariant Enforcement (Prerequisites must precede dependents)
    let violationFound = true;
    let guardIterations = 0;
    while (violationFound && guardIterations < 20) {
      violationFound = false;
      for (const c of courses) {
        const cCol = courseColumnMap[c.id] ?? 0;
        const prereqs = prereqGraph.get(c.id) || [];
        for (const pId of prereqs) {
          const pCol = courseColumnMap[pId] ?? 0;
          if (cCol <= pCol) {
            // Dependent course c is placed before or in same semester as prerequisite p
            const newCCol = Math.min(maxRegularSemesters - 1, pCol + 1);
            courseColumnMap[c.id] = newCCol;
            violationFound = true;
          }
        }
      }
      guardIterations++;
    }

    // Step 6: Map assigned column numbers to Arabic semester labels
    courses.forEach((c) => {
      const col = courseColumnMap[c.id] ?? 0;
      const safeCol = Math.min(maxRegularSemesters - 1, Math.max(0, col));
      courseColumnMap[c.id] = safeCol;
      courseSemesterMap[c.id] =
        allowedSemesterNames[safeCol] || REGULAR_SEMESTER_NAMES[safeCol];
    });
  }

  return {
    courseSemesterMap,
    courseColumnMap,
    isAutoGenerated,
    maxYears,
    maxRegularSemesters,
    allowedSemesterNames,
  };
}

/**
 * Returns elective slot configurations tailored to the active major.
 * For CSE, returns the standard 8 slots. For other majors, avoids polluting with CSE-specific course IDs.
 */
export function getMajorElectiveSlots(
  majorId?: string,
  totalCredits?: number,
): {
  electiveDefs: Record<
    string,
    { id: string; category: string; label: string; defaultCourseId: string }
  >;
  semesterSlots: Record<string, string[]>;
} {
  if (isCseMajor(majorId)) {
    return {
      electiveDefs: ELECTIVE_SLOTS_DEFS,
      semesterSlots: SEMESTER_ELECTIVE_SLOTS,
    };
  }

  // Non-CSE majors: return empty slot maps so the UI does not inject foreign CSE elective cards
  return {
    electiveDefs: {},
    semesterSlots: {},
  };
}
